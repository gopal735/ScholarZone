import { useEffect, useRef, useState } from 'react'
import { Link } from 'react-router-dom'
import { askAIAssistant, isAIEnabled, checkAIAvailability } from '../services/aiAssistant'
import './AIAssistantPage.css'

const SUGGESTED_PROMPTS = [
  'Find fully funded Master\'s scholarships in Germany',
  'Compare DAAD and Erasmus Mundus funding',
  'What are the eligibility requirements for Chevening?',
  'Which scholarships have deadlines in the next 30 days?',
  'How do I write a strong Statement of Purpose for MEXT?',
  'What documents are needed for Australia Awards?',
  'Find PhD scholarships with stipend in Europe',
  'Explain the application process for Commonwealth Scholarship',
]

export default function AIAssistantPage() {
  const [messages, setMessages] = useState([])
  const [input, setInput] = useState('')
  const [isLoading, setIsLoading] = useState(false)
  const [aiAvailable, setAiAvailable] = useState(false)
  const [aiEnabled, setAiEnabled] = useState(isAIEnabled())
  const messagesEndRef = useRef(null)
  const inputRef = useRef(null)

  useEffect(() => {
    checkAIAvailability().then(available => {
      setAiAvailable(available)
      setAiEnabled(available)
    })
  }, [])

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [messages])

  const handleSubmit = async (e) => {
    e.preventDefault()
    if (!input.trim() || isLoading) return

    const userMessage = input.trim()
    setInput('')
    setIsLoading(true)

    setMessages(prev => [...prev, { role: 'user', content: userMessage }])

    try {
      const response = await askAIAssistant({
        question: userMessage,
        context: {
          conversationHistory: messages.slice(-6).map(m => ({
            role: m.role,
            content: m.content
          }))
        }
      })

      setMessages(prev => [...prev, {
        role: 'assistant',
        content: response.answer,
        sources: response.sources,
        grounded: response.grounded
      }])
    } catch (error) {
      const aiError = error
      setMessages(prev => [...prev, {
        role: 'assistant',
        content: aiError.error || 'An unexpected error occurred.',
        error: aiError
      }])
    } finally {
      setIsLoading(false)
      inputRef.current?.focus()
    }
  }

  const handleSuggestionClick = (prompt) => {
    setInput(prompt)
    inputRef.current?.focus()
  }

  const handleRetry = () => {
    const lastUserMessage = [...messages].reverse().find(m => m.role === 'user')
    if (lastUserMessage) {
      setMessages(prev => prev.filter(m => m !== lastUserMessage))
      handleSubmit(new Event('submit'))
    }
  }

  return (
    <div className="ai-assistant-page">
      <header className="ai-assistant-header">
        <div className="ai-assistant-title">
          <h1>ScholarZone AI Assistant</h1>
          <p className="ai-assistant-subtitle">
            {aiEnabled && aiAvailable
              ? 'AI-powered scholarship discovery and guidance'
              : 'Grounded scholarship assistance from ScholarZone records'}
          </p>
        </div>
        <div className="ai-assistant-status">
          <span className={`status-badge ${aiEnabled && aiAvailable ? 'ai-active' : 'grounded-mode'}`}>
            {aiEnabled && aiAvailable ? '🤖 AI Active' : '📋 Grounded Mode'}
          </span>
          {!aiAvailable && aiEnabled && (
            <button
              type="button"
              className="retry-ai-btn"
              onClick={() => checkAIAvailability().then(setAiAvailable)}
            >
              Retry AI Connection
            </button>
          )}
        </div>
      </header>

      <div className="ai-assistant-disclaimer" role="note">
        <strong>Important:</strong>
        {aiEnabled && aiAvailable
          ? 'This AI assistant uses a large language model. Answers may contain inaccuracies. Always verify scholarship details on official provider websites. Source citations are provided where available.'
          : 'Running in grounded mode. Answers are composed from verified ScholarZone scholarship records — not generated by an LLM. No AI inference is taking place.'}
      </div>

      <div className="ai-assistant-chat" role="log" aria-live="polite" aria-label="Conversation">
        {messages.length === 0 ? (
          <div className="ai-assistant-welcome">
            <div className="welcome-content">
              <h2>How can I help with your scholarship search?</h2>
              <p>Ask me about scholarships, eligibility, deadlines, funding, applications, or anything else.</p>

              <div className="suggested-prompts" role="list" aria-label="Suggested questions">
                {SUGGESTED_PROMPTS.map((prompt, i) => (
                  <button
                    key={i}
                    type="button"
                    className="suggested-prompt"
                    onClick={() => handleSuggestionClick(prompt)}
                    role="listitem"
                  >
                    {prompt}
                  </button>
                ))}
              </div>
            </div>
          </div>
        ) : (
          <>
            {messages.map((message, index) => (
              <div key={index} className={`message message--${message.role}`}>
                <div className="message-content">
                  {message.role === 'assistant' && message.grounded !== undefined && (
                    <span className={`grounded-badge ${message.grounded ? 'grounded' : 'ai-generated'}`}>
                      {message.grounded ? '📋 Grounded in ScholarZone data' : '🤖 AI Generated'}
                    </span>
                  )}
                  <div className="message-text" dangerouslySetInnerHTML={{ __html: message.content.replace(/\n/g, '<br>') }} />

                  {message.sources && message.sources.length > 0 && (
                    <div className="message-sources">
                      <strong>Sources:</strong>
                      <ul>
                        {message.sources.map((source, i) => (
                          <li key={i}>
                            {source.type === 'scholarship' && source.url ? (
                              <a href={source.url} target="_blank" rel="noopener noreferrer">
                                {source.title}
                              </a>
                            ) : (
                              source.title
                            )}
                            {source.type !== 'scholarship' && ` (${source.type})`}
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}

                  {message.error && (
                    <div className="message-error">
                      <p>{message.error.error}</p>
                      {message.error.retryable && (
                        <button type="button" className="retry-btn" onClick={handleRetry}>
                          Try Again
                        </button>
                      )}
                    </div>
                  )}
                </div>
              </div>
            ))}
            <div ref={messagesEndRef} />
          </>
        )}

        {isLoading && (
          <div className="message message--assistant message--loading">
            <div className="message-content">
              <div className="loading-indicator">
                <span></span><span></span><span></span>
              </div>
              <p className="loading-text">
                {aiEnabled && aiAvailable ? 'AI is thinking...' : 'Searching ScholarZone records...'}
              </p>
            </div>
          </div>
        )}
      </div>

      <form className="ai-assistant-input" onSubmit={handleSubmit}>
        <label htmlFor="ai-input" className="visually-hidden">Ask a question</label>
        <textarea
          ref={inputRef}
          id="ai-input"
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder={aiEnabled && aiAvailable
            ? 'Ask anything about scholarships... (e.g., "Find fully funded Master\'s in Germany with October deadlines")'
            : 'Ask about scholarships using ScholarZone data... (e.g., "What are the deadlines for Chevening and DAAD?")'}
          rows={1}
          disabled={isLoading}
          onKeyDown={(e) => {
            if (e.key === 'Enter' && !e.shiftKey) {
              e.preventDefault()
              handleSubmit(e)
            }
          }}
        />
        <button
          type="submit"
          disabled={!input.trim() || isLoading}
          className="send-btn"
          aria-label="Send question"
        >
          <svg viewBox="0 0 24 24" aria-hidden="true" width="20" height="20">
            <path d="M2.01 21L23 12 2.01 3 2 10l15 2-15 2z" />
          </svg>
        </button>
      </form>

      <footer className="ai-assistant-footer">
        <p>
          <Link to="/scholarships">Browse Directory</Link> ·
          <Link to="/match">Check Eligibility</Link> ·
          <Link to="/mentor">Grounded Mentor</Link> ·
          <Link to="/compare">Compare Scholarships</Link>
        </p>
        <p className="privacy-note">
          Your questions are processed and discarded. No conversation history is stored.
        </p>
      </footer>
    </div>
  )
}