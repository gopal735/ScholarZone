export const DICTIONARY = { bn, en }

/**
 * Resolve a key for a language, falling back to English then to the key itself.
 *
 * A missing Bangla key is a real gap, so it surfaces as the English string
 * rather than a blank: an untranslated label is recoverable, an empty one is
 * not.
 */
export function translate(language, key) {
  const primary = DICTIONARY[language]?.[key]
  if (typeof primary === 'string' && primary !== '') return primary
  const fallback = DICTIONARY.en[key]
  return typeof fallback === 'string' ? fallback : key
}

export { en as enStrings, bn as bnStrings }
